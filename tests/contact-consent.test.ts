import { describe, it, after } from 'node:test';
import assert from 'node:assert/strict';
import { prisma } from '../lib/db';
import { contactSubmissionSchema } from '../lib/validation';
import {
  ContactService,
  PRIVACY_NOTICE_VERSION,
  CONSENT_PURPOSE_ENQUIRY,
} from '../lib/services/contactService';

describe('Contact Form Consent & Privacy Verification Suite', () => {
  const testEmailPrefix = `test-consent-${Date.now()}@example.com`;

  after(async () => {
    // Clean up all test submissions created during this test run
    await prisma.contactSubmission.deleteMany({
      where: {
        email: {
          contains: 'test-consent-',
        },
      },
    });
  });

  it('1. Accepted Consent: Validates payload and persists server-generated consent metadata', async () => {
    const validPayload = {
      name: 'Rohan Sharma',
      email: testEmailPrefix,
      businessName: 'Acme Studio',
      helpDetails: 'Need a custom Next.js web application with 3D animation.',
      budget: 'Web Development',
      consentGiven: true,
    };

    // Schema validation succeeds
    const validated = contactSubmissionSchema.parse(validPayload);
    assert.strictEqual(validated.consentGiven, true);

    // Submission persists to SQLite DB
    const beforeTime = Date.now() - 1000;
    const submission = await ContactService.createSubmission(validPayload, '127.0.0.1');
    const afterTime = Date.now() + 1000;

    assert.ok(submission.id, 'Submission must generate a unique ID');
    assert.strictEqual(submission.name, 'Rohan Sharma');
    assert.strictEqual(submission.email, testEmailPrefix);
    assert.strictEqual(submission.consentGiven, true, 'consentGiven must be true in database');

    // Verify server-generated timestamp
    assert.ok(submission.consentAt instanceof Date, 'consentAt must be a valid Date object');
    const consentTime = submission.consentAt.getTime();
    assert.ok(
      consentTime >= beforeTime && consentTime <= afterTime,
      `consentAt timestamp (${consentTime}) must be generated by the server during creation`
    );

    // Verify notice version and purpose are locked to server constants
    assert.strictEqual(
      submission.consentVersion,
      PRIVACY_NOTICE_VERSION,
      'consentVersion must match server PRIVACY_NOTICE_VERSION'
    );
    assert.strictEqual(
      submission.consentPurpose,
      CONSENT_PURPOSE_ENQUIRY,
      'consentPurpose must match server CONSENT_PURPOSE_ENQUIRY'
    );
  });

  it('2. Missing Consent: Rejects payload when consentGiven is omitted', async () => {
    const missingConsentPayload = {
      name: 'Jane Doe',
      email: 'jane@example.com',
      helpDetails: 'Inquiry without consent property.',
    };

    assert.throws(
      () => contactSubmissionSchema.parse(missingConsentPayload),
      (err: any) => {
        assert.strictEqual(err.name, 'ZodError');
        const issue = err.issues?.[0];
        assert.ok(
          issue?.message.includes('Explicit privacy consent is required') ||
          issue?.message.includes('consent'),
          `Unexpected error message: ${issue?.message}`
        );
        return true;
      }
    );

    await assert.rejects(
      async () => await ContactService.createSubmission(missingConsentPayload, '127.0.0.1'),
      /Explicit privacy consent is required/
    );
  });

  it('3. False Consent: Rejects payload when consentGiven is explicitly false', async () => {
    const falseConsentPayload = {
      name: 'Unconsenting User',
      email: 'no-consent@example.com',
      helpDetails: 'Explicitly refused to give consent.',
      consentGiven: false,
    };

    assert.throws(
      () => contactSubmissionSchema.parse(falseConsentPayload),
      (err: any) => {
        assert.strictEqual(err.name, 'ZodError');
        const issue = err.issues?.[0];
        assert.ok(
          issue?.message.includes('Explicit privacy consent is required'),
          `Unexpected error message: ${issue?.message}`
        );
        return true;
      }
    );

    await assert.rejects(
      async () => await ContactService.createSubmission(falseConsentPayload, '127.0.0.1'),
      /Explicit privacy consent is required/
    );
  });

  it('4. Malformed Consent: Rejects truthy strings, numbers, or objects', async () => {
    const malformedVariants = [
      { consentGiven: 'true' },
      { consentGiven: 'yes' },
      { consentGiven: 1 },
      { consentGiven: null },
      { consentGiven: {} },
      { consentGiven: [] },
    ];

    for (const variant of malformedVariants) {
      const payload = {
        name: 'Attacker Test',
        email: 'attacker@example.com',
        helpDetails: 'Trying to bypass boolean check.',
        ...variant,
      };

      assert.throws(
        () => contactSubmissionSchema.parse(payload),
        (err: any) => {
          assert.strictEqual(err.name, 'ZodError');
          return true;
        },
        `Expected schema to reject malformed consentGiven: ${JSON.stringify(variant)}`
      );
    }
  });

  it('5. Anti-Spoofing: Client cannot override server timestamp or purpose', async () => {
    const spoofAttemptPayload = {
      name: 'Spoof Attacker',
      email: `test-consent-spoof-${Date.now()}@example.com`,
      helpDetails: 'Trying to inject fake consent timestamp and version.',
      consentGiven: true,
      // Client tries to spoof server metadata
      consentAt: new Date('1990-01-01T00:00:00Z'),
      consentVersion: 'v999-malicious-version',
      consentPurpose: 'UNAUTHORIZED_SPAM_PURPOSE',
    };

    const submission = await ContactService.createSubmission(spoofAttemptPayload, '127.0.0.1');

    // Ensure server-generated values prevailed
    assert.notStrictEqual(
      submission.consentVersion,
      'v999-malicious-version',
      'Client must NOT be able to overwrite consentVersion'
    );
    assert.strictEqual(
      submission.consentVersion,
      PRIVACY_NOTICE_VERSION,
      'consentVersion must be set strictly by the server'
    );
    assert.strictEqual(
      submission.consentPurpose,
      CONSENT_PURPOSE_ENQUIRY,
      'consentPurpose must be set strictly by the server'
    );

    const year = submission.consentAt?.getFullYear();
    assert.ok(
      year && year >= 2026,
      `consentAt timestamp must be current server time, got year: ${year}`
    );
  });

  it('6. Backward Compatibility: Historical records without consent remain valid', async () => {
    // Directly insert a record without consent metadata to simulate pre-existing historical data
    const legacyRecord = await prisma.contactSubmission.create({
      data: {
        name: 'Legacy Lead 2024',
        email: `test-consent-legacy-${Date.now()}@example.com`,
        helpDetails: 'Historical submission before DPDP Act implementation.',
        status: 'NEW',
        // consentGiven defaults to false, other fields null
      },
    });

    assert.ok(legacyRecord.id);
    assert.strictEqual(legacyRecord.consentGiven, false);
    assert.strictEqual(legacyRecord.consentAt, null);
    assert.strictEqual(legacyRecord.consentVersion, null);
    assert.strictEqual(legacyRecord.consentPurpose, null);

    // Ensure ContactService.getAllSubmissions() reads historical data without throwing
    const all = await ContactService.getAllSubmissions();
    const foundLegacy = all.find((s) => s.id === legacyRecord.id);
    assert.ok(foundLegacy, 'Legacy record must be returned in getAllSubmissions() without error');
    assert.strictEqual(foundLegacy.consentGiven, false);
  });

  it('7. API Route Handler (POST /api/contact): Rejects missing consent and accepts valid consent', async () => {
    const { POST } = await import('../app/api/contact/route');

    // Case A: Missing consent
    const reqMissing = new Request('http://localhost:3000/api/contact', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        name: 'API Tester',
        email: `test-consent-api-missing-${Date.now()}@example.com`,
        helpDetails: 'Testing API without consent',
      }),
    });
    const resMissing = await POST(reqMissing);
    assert.strictEqual(resMissing.status, 400);
    const bodyMissing = await resMissing.json();
    assert.ok(
      bodyMissing.error?.includes('Explicit privacy consent is required'),
      `Expected consent error message, got: ${bodyMissing.error}`
    );

    // Case B: Explicitly false consent
    const reqFalse = new Request('http://localhost:3000/api/contact', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        name: 'API Tester',
        email: `test-consent-api-false-${Date.now()}@example.com`,
        helpDetails: 'Testing API with false consent',
        consentGiven: false,
      }),
    });
    const resFalse = await POST(reqFalse);
    assert.strictEqual(resFalse.status, 400);

    // Case C: Valid consent given
    const reqValid = new Request('http://localhost:3000/api/contact', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        name: 'API Tester',
        email: `test-consent-api-valid-${Date.now()}@example.com`,
        helpDetails: 'Testing API with valid consent',
        consentGiven: true,
      }),
    });
    const resValid = await POST(reqValid);
    assert.strictEqual(resValid.status, 200);
    const bodyValid = await resValid.json();
    assert.strictEqual(bodyValid.success, true);
    assert.ok(bodyValid.submissionId, 'API must return generated submissionId');

    // Verify persisted database record from API route
    const dbRecord = await prisma.contactSubmission.findUnique({
      where: { id: bodyValid.submissionId },
    });
    assert.ok(dbRecord);
    assert.strictEqual(dbRecord.consentGiven, true);
    assert.strictEqual(dbRecord.consentVersion, PRIVACY_NOTICE_VERSION);
    assert.strictEqual(dbRecord.consentPurpose, CONSENT_PURPOSE_ENQUIRY);
    assert.ok(dbRecord.consentAt instanceof Date);
  });
});
